"""Generate `docs/feature_book.md`: what every feature means, and what it does not.

Design decision embodied here: the book is **generated from the panel and the definitions data**,
not written by hand. A hand-written book drifts the moment a window or a gate changes, and the
Phase 2 exit condition is precisely that every feature has a definition *and an honest caveat*.
Generating it means the caveat shown to a reader is the one the code enforces.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from ..config import Settings
from .definitions import FEATURES
from .panel import Panel

# The structural limits from SPEC.md 2.4, restated in every report so no number can be read
# without them. Values are measured on the full corpus and marked as such.
LIMITS = [
    "One regime only (2021-09-30 -> 2022-09-29, 252 sessions): nothing here generalises beyond it.",
    "The independent unit is the ticker-day, not the tweet. 80,793 tweets are not 80,793 observations.",
    "TSLA is 46.3% of the corpus, so a pooled statistic is nearly a TSLA statistic; pooled results are always shown with a TSLA-excluded variant.",
    "28.5% of rows are cross-posted text; AMZN, MSFT, PG, F and NOC are 100% cross-posted and are descriptive-only (tier C).",
    "55.8% of rows are promo-shaped and most contain a t.co link.",
    "~49% of tweets roll to the next session (after the 16:00 ET close or on a non-trading date).",
    "There is no author field, so author-level, bot-detection and unique-user metrics are impossible, not deferred.",
    "A tweet's timestamp is not the time the market learned the news.",
]


def _series_stats(panel: pd.DataFrame, column: str) -> str:
    """Return a one-line coverage summary for a column: non-null units and min/median/max."""
    if column not in panel.columns:
        return "not in the panel"
    values = pd.to_numeric(panel[column], errors="coerce")
    if values.notna().sum() == 0:
        return f"0/{len(panel)} units populated"
    return (
        f"{int(values.notna().sum())}/{len(panel)} units populated; "
        f"min {values.min():.4g}, median {values.median():.4g}, max {values.max():.4g}"
    )


def render_feature_book(panel: Panel, settings: Settings) -> str:
    """Render the whole feature book as Markdown text."""
    frame = panel.panel
    meta = panel.meta
    lines: list[str] = []
    add = lines.append

    add("# Feature book")
    add("")
    add(
        "Generated by `run.py features`. Every definition below is the one the code applies, and "
        "every caveat is one the code enforces — both live in `src/eda_demo/features/definitions.py`."
    )
    add("")
    add(f"- Dataset slice: **{meta.get('dataset', settings.dataset_name)}**")
    add(f"- `data_version`: `{panel.data_version}`  (data hash + config + lexicon id + code version)")
    add(f"- Lexicon: `{meta.get('lexicon', {}).get('lexicon_id', '?')}` ({meta.get('lexicon', {}).get('source', '?')}, {meta.get('lexicon', {}).get('terms', 0)} terms)")
    add(f"- Sessions: {meta.get('sessions', '?')}  |  panel rows (ticker-sessions): {meta.get('n_units', len(frame)):,}")
    split = meta.get("split", {})
    if split:
        add(
            f"- Discovery: {split.get('discovery_sessions')} sessions "
            f"({split.get('discovery_start')} -> {split.get('discovery_end')})  |  "
            f"Holdout: {split.get('holdout_sessions')} sessions "
            f"({split.get('holdout_start')} -> {split.get('holdout_end')})"
        )
    add("")

    add("## Quality gates, as measured here")
    add("")
    gates = [
        ("units with a sentiment score", meta.get("units_with_sentiment")),
        ("units below min_tweets_per_day", meta.get("units_low_coverage")),
        (
            "units that would clear the minimum on ALL text (diagnostic only)",
            meta.get("units_meeting_min_on_all_text"),
        ),
        ("units excluded from inference", meta.get("units_excluded_from_tests")),
        ("cells with no tweets at all", meta.get("attention", {}).get("cells_with_no_tweets")),
    ]
    for label, value in gates:
        add(f"- {label}: **{value}**")
    add("")

    add("## Coverage tiers")
    add("")
    add("| Ticker | Tier | Own-text share (panel) |")
    add("|---|---|---|")
    tiers = meta.get("tiers", {}).get("by_ticker", {})
    share = frame.groupby("ticker")["own_text_share"].mean()
    for ticker in sorted(tiers):
        add(f"| {ticker} | {tiers[ticker]} | {share.get(ticker, float('nan')):.3f} |")
    add("")
    add(
        "Tier A: per-ticker inference allowed. Tier B: descriptive, or per-ticker with own-text-only "
        "and the fan-out share printed. Tier C: descriptive coverage only — its text belongs to other "
        "tickers, so its per-ticker sentiment would be measuring the generic pool."
    )
    add("")

    for family in ("sentiment", "attention", "price", "quality"):
        heading = {
            "sentiment": "Sentiment family (7 published measures)",
            "attention": "Attention family (7 published measures)",
            "price": "Price features",
            "quality": "Quality flags",
        }[family]
        add(f"## {heading}")
        add("")
        add("| Feature | Measure | Definition | Caveat / limit | In this run |")
        add("|---|---|---|---|---|")
        for name, spec in FEATURES.items():
            if spec["family"] != family:
                continue
            add(
                f"| `{name}` | {spec.get('headline') or '—'} | {spec['definition']} | "
                f"{spec['caveat']} | {_series_stats(frame, name)} |"
            )
        add("")

    add("## Method notes")
    add("")
    scoring = meta.get("scoring", {})
    add(
        f"- Polarity = (1 - w) * VADER compound + w * tanh(lexicon weight sum), with w = "
        f"`sentiment.lexicon_weight` = {scoring.get('lexicon_weight', '?')}. VADER available: "
        f"{scoring.get('vader_available', '?')}."
    )
    add(
        f"- Label band: +/-{scoring.get('label_band', '?')} (VADER's convention). Negation: a negator "
        f"within {scoring.get('negation_window', '?')} tokens flips a term and damps it by "
        f"{scoring.get('negation_damp', '?')}."
    )
    add(
        f"- Missing VADER would downgrade the method to lexicon-only rather than fail the run; that is "
        f"recorded in `scoring.method`."
    )
    add(
        "- Sarcasm is not modelled. `sent_sarcasm_share` reports how much of the cell carries a marker, "
        "so the limit is visible on the card instead of being argued about later."
    )
    add(
        "- Attention z-scores compare day d with days strictly before it (`shift(1)`); forward returns "
        "are null, not wrapped, in the last h sessions."
    )
    add("")

    add("## Structural limits, restated")
    add("")
    for limit in LIMITS:
        add(f"- {limit}")
    add("")
    add("These are limits of the dataset, not of the pipeline. `supported` in a finding means")
    add("\"passed this demo's checks\" and nothing stronger; nothing here is trading advice.")
    add("")

    add("## Warnings carried into this run")
    add("")
    warnings = meta.get("canonical_report", {}).get("warnings", []) or []
    for warning in warnings:
        add(f"- {warning}")
    if not warnings:
        add("- none")
    add("")
    return "\n".join(lines)


def write_feature_book(panel: Panel, settings: Settings, path: Path) -> Path:
    """Write the feature book to `path` and return it."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_feature_book(panel, settings), encoding="utf-8")
    return path


def feature_overview(panel: Panel) -> dict[str, Any]:
    """Return the few numbers the terminal overview prints about the feature layer."""
    frame = panel.panel
    return {
        "units": len(frame),
        "tweets_in_panel": int(frame["n_tweets"].sum()),
        "own_texts": int(frame["n_texts_own"].sum()),
        "sentiment_units": int(frame["sent_net"].notna().sum()),
        "low_coverage_units": int(frame["low_coverage"].sum()),
        "sustained_spikes": int(frame["spike_sustained"].sum()),
    }
